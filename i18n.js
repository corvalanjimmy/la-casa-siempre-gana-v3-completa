function t(clave){
  var d = DIC[IDIOMA] || DIC.es;
  return (d[clave] !== undefined) ? d[clave] : (DIC.es[clave] !== undefined ? DIC.es[clave] : clave);
}
function pintar(){
  document.querySelectorAll('[data-t]').forEach(function(el){
    var k = el.getAttribute('data-t');
    if(el.hasAttribute('data-t-html')) el.innerHTML = t(k); else el.textContent = t(k);
  });
  document.querySelectorAll('[data-t-ph]').forEach(function(el){
    el.setAttribute('placeholder', t(el.getAttribute('data-t-ph')));
  });
  document.querySelectorAll('[data-t-title]').forEach(function(el){
    el.setAttribute('title', t(el.getAttribute('data-t-title')));
  });
  document.documentElement.lang = IDIOMA;
}

